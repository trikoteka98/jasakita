export const getCategory = (id) => categories.find((c) => c.id === id)
export const getProvider = (id) => providers.find((p) => p.id === id)

// Penyedia yang melayani distrik tertentu
export const providersCovering = (district) =>
  providers.filter((p) => p.coverage.includes(district))

export const formatRupiah = (n) => 'Rp ' + n.toLocaleString('id-ID')
export const phoneToWa = (phone) => 'https://wa.me/' + phone
